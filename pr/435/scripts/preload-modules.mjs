#!/usr/bin/env node
// scripts/preload-modules.mjs — let a deployed LUCID fetch its whole startup
// module graph AT ONCE instead of discovering it one import level at a time.
//
//   node scripts/preload-modules.mjs <site-dir>
//
// Rewrites <site-dir>/index.html IN PLACE: right after the importmap it inserts one
// `<link rel="modulepreload">` per module the page's module scripts STATICALLY
// import — transitively, through relative specifiers and importmap entries — plus
// the cross-origin (CDN) modules that graph names.
//
// Why: without it the browser learns of a module only after its importer has
// arrived and been parsed, so app.js -> pose/initialization.js -> ... is a chain
// of six request round trips (measured on the 111-file graph: depth 1..6). On a
// cold start every one of those is a CDN miss, and a cold start is common: every
// deploy changes every `?v=` URL (scripts/stamp-version.mjs), and Cloudflare
// keeps a GitHub Pages object at the edge only as long as the origin's 10-minute
// max-age. With the list in the head all ~110 requests start while the head is
// still being parsed.
//
// The list is DERIVED, not maintained: this walks the files actually being
// deployed, so it cannot go stale. Run it AFTER stamp-version.mjs (its CLI does
// that): the walk then reads the stamped specifiers, so each preload names the
// exact URL its importer will ask for — an ES module's identity is its URL, and a
// preload under any other URL would be a second download that nothing uses.
//
// Not preloaded: dynamic `import()` (lazy by design), workers (another realm),
// and the classic `<script src>` tags (the parser already fetches those).
// Idempotent: an index.html that already has the generated block is rewritten
// with a fresh one.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const BASE = 'https://site.invalid/';            // a stand-in origin for URL resolution
const BEGIN = '<!-- modulepreload: generated by scripts/preload-modules.mjs -->';
const END = '<!-- /modulepreload -->';

/** Strip comments so a commented-out import is not followed. Strings are left alone. */
function stripComments(src) {
    return src.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1');
}

/** The specifiers a module imports STATICALLY: `import … from`, `import '…'`, `export … from`. */
export function staticSpecifiers(src) {
    const out = [];
    const re = /(?:^|[;}\s])(?:import|export)\s*(?:[\w$*{}\s,]*?\bfrom\s*)?(['"])([^'"\n]+)\1/g;
    let m;
    const s = stripComments(src);
    while ((m = re.exec(s))) {
        // `import(` is dynamic: the regex cannot match it (a quote must follow
        // `import` + whitespace), which is exactly the exclusion we want.
        out.push(m[2]);
    }
    return out;
}

/**
 * The page's startup module graph, in discovery (breadth-first) order.
 * Returns { local: ['./x.js?v=…', …], remote: ['https://…', …], missing: [...] }.
 */
export function moduleGraph(root, htmlRel = 'index.html') {
    const html = fs.readFileSync(path.join(root, htmlRel), 'utf8');
    const pageUrl = new URL(htmlRel, BASE).href;
    const mapMatch = html.match(/<script\b[^>]*\btype\s*=\s*["']importmap["'][^>]*>([\s\S]*?)<\/script>/i);
    const imports = mapMatch ? (JSON.parse(mapMatch[1]).imports || {}) : {};
    const resolve = (spec, from) => {
        if (Object.prototype.hasOwnProperty.call(imports, spec)) return new URL(imports[spec], pageUrl).href;
        if (/^[a-z][\w+.-]*:/i.test(spec)) return spec;             // absolute (https:, data:, …)
        if (/^(\.{0,2}\/)/.test(spec)) return new URL(spec, from).href;
        return null;                                                // bare and unmapped: the browser would throw too
    };
    const roots = [];
    const tag = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
    let t;
    while ((t = tag.exec(html))) {
        const attrs = t[1];
        if (!/\btype\s*=\s*["']module["']/i.test(attrs)) continue;
        const src = attrs.match(/\bsrc\s*=\s*(["'])([^"']+)\1/i);
        if (src) roots.push({ url: new URL(src[2], pageUrl).href, root: true });
        else for (const spec of staticSpecifiers(t[2])) { const u = resolve(spec, pageUrl); if (u) roots.push({ url: u, root: false }); }
    }
    const seen = new Set(), order = [], remote = [], missing = [];
    const rootUrls = new Set(roots.filter(r => r.root).map(r => r.url));
    const queue = roots.map(r => r.url);
    while (queue.length) {
        const url = queue.shift();
        if (seen.has(url)) continue;
        seen.add(url);
        if (!url.startsWith(BASE)) { if (/^https?:/.test(url)) remote.push(url); continue; }
        const file = path.join(root, decodeURIComponent(new URL(url).pathname.slice(1)));
        if (!fs.existsSync(file)) { missing.push(url); continue; }
        if (!rootUrls.has(url)) order.push(url);                    // a <script src> root is fetched by its own tag
        for (const spec of staticSpecifiers(fs.readFileSync(file, 'utf8'))) {
            const u = resolve(spec, url);
            if (u) queue.push(u);
        }
    }
    const rel = (u) => './' + u.slice(BASE.length);
    return { local: order.map(rel), remote, missing };
}

/** The `<link rel="modulepreload">` block for a graph. */
export function preloadBlock(graph, indent = '    ') {
    const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
    const lines = [...graph.local, ...graph.remote].map(u => `${indent}<link rel="modulepreload" href="${esc(u)}">`);
    return `${indent}${BEGIN}\n${lines.join('\n')}\n${indent}${END}`;
}

/** Insert (or refresh) the block in <root>/<htmlRel>, right after the importmap. */
export function preloadSite(root, htmlRel = 'index.html') {
    const file = path.join(root, htmlRel);
    let html = fs.readFileSync(file, 'utf8');
    const old = new RegExp('[ \\t]*' + BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\n?');
    html = html.replace(old, '');
    fs.writeFileSync(file, html);                                   // walk the page without a stale block
    const graph = moduleGraph(root, htmlRel);
    // The importmap must be parsed before any module fetch starts — a modulepreload
    // included — or Chrome ignores the map. So the block goes directly after it.
    const mapEnd = html.search(/<script\b[^>]*\btype\s*=\s*["']importmap["'][^>]*>[\s\S]*?<\/script>/i);
    if (mapEnd < 0) throw new Error(htmlRel + ': no importmap to anchor the preloads after');
    const close = html.indexOf('</script>', mapEnd) + '</script>'.length;
    html = html.slice(0, close) + '\n' + preloadBlock(graph) + html.slice(close);
    fs.writeFileSync(file, html);
    return graph;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const [root] = process.argv.slice(2);
    if (!root) { console.error('usage: node scripts/preload-modules.mjs <site-dir>'); process.exit(2); }
    const g = preloadSite(path.resolve(root));
    console.log(`preload-modules: ${g.local.length} same-site + ${g.remote.length} CDN modulepreload links in ${root}/index.html`);
    if (g.missing.length) {
        console.error('preload-modules: statically imported files that do not exist:');
        g.missing.forEach(u => console.error('  ' + u));
        process.exit(1);
    }
}
